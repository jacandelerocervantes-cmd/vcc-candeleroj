    W("* El nulo con el submuestreo a 400 **concentrado en una sola guia**, que es la")
    W("  forma de la entrega (una perturbacion = un constructo).")
    W("* Las otras cinco metricas del preset: este reporte solo toca la puerta de")
    W("  significancia (el conjunto DE). `pds_cosine`, `expr_mse_unbiased_capped_norm`,")
