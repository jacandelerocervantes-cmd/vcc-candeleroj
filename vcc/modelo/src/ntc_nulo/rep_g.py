    W("    alcanzan para verificarla; pero la MAGNITUD del `delta nnz` y de la suma de")
    W("    cuentas se midio en 6 pares (emision, blanco) y una sola muestra de 400")
    W("    celulas de un solo contexto (`D`, semilla `20274999`).")
    W("13. **La cobertura de la Parte 0b es de SIMBOLOS, no de identidad de gen.** Se")
    W("    cruzaron nombres de gen con nombres de gen. Un simbolo que cambio de")
    W("    nomenclatura entre gwps y el panel del reto cuenta como ausente aunque sea")
    W("    el mismo gen. No se uso ningun mapa de alias, y cuantos casos hay no se midio.")
    W("")
    W("## Lo que no se midio")
